// Command genindex writes the public API index from the generated manifests.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"strings"
)

type operation struct {
	Path       string `json:"path"`
	HTTPMethod string `json:"http_method"`
	Scope      string `json:"scope"`
	Service    string `json:"service"`
	Method     string `json:"method"`
	DocURL     string `json:"doc_url"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	var out bytes.Buffer
	out.WriteString("# API index\n\nGenerated by `go generate .`; do not edit manually.\n\n")
	out.WriteString("Each listed operation is covered by the contract test suite. ")
	out.WriteString("Coverage means method and route coverage of the captured inventory, not complete field schemas or live-server verification. ")
	out.WriteString("See [contract provenance and limitations](../spec/README.md).\n\n")
	for _, version := range []string{"v3", "v1", "v2"} {
		file := "operations.json"
		if version != "v3" {
			file = version + "/" + file
		}
		data, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		var operations []operation
		if err := json.Unmarshal(data, &operations); err != nil {
			return err
		}
		fmt.Fprintf(&out, "## %s — %d operations\n\n", version, len(operations))
		out.WriteString("| Service method | HTTP endpoint | Reference |\n| --- | --- | --- |\n")
		for _, op := range operations {
			selector := "client."
			if op.Scope == "org" {
				selector += "Organization(orgID)."
			} else if op.Scope == "enterprise" {
				selector += "Enterprise()."
			}
			if op.Service != "Client" {
				selector += op.Service + "."
			}
			selector += op.Method
			link := ""
			if op.DocURL != "" {
				link = "[Source](" + strings.ReplaceAll(op.DocURL, ")", "%29") + ")"
			}
			fmt.Fprintf(&out, "| `%s` | `%s %s` | %s |\n", selector, op.HTTPMethod, op.Path, link)
		}
		out.WriteByte('\n')
	}
	return os.WriteFile("docs/API.md", append(bytes.TrimRight(out.Bytes(), "\n"), '\n'), 0o644)
}
