// Command genmodels generates Go model types from an OpenAPI JSON document.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path"
	"sort"
	"strconv"
	"strings"

	"devingo/internal/codegen"
)

type document struct {
	Components struct {
		Schemas map[string]*schema `json:"schemas"`
	} `json:"components"`
}

type schema struct {
	Ref                  string             `json:"$ref"`
	Description          string             `json:"description"`
	Type                 string             `json:"type"`
	Format               string             `json:"format"`
	Nullable             bool               `json:"nullable"`
	Enum                 []json.RawMessage  `json:"enum"`
	Properties           map[string]*schema `json:"properties"`
	Required             []string           `json:"required"`
	Items                *schema            `json:"items"`
	AdditionalProperties json.RawMessage    `json:"additionalProperties"`
	AnyOf                []*schema          `json:"anyOf"`
	OneOf                []*schema          `json:"oneOf"`
	AllOf                []*schema          `json:"allOf"`
	PrefixItems          []*schema          `json:"prefixItems"`
}

type generator struct {
	packageName    string
	optionalImport string
	schemas        map[string]*schema
	declared       map[string]bool
	declaredSchema map[string]*schema
	componentNames map[string]string
	decls          []string
	usesJSON       bool
	usesOptional   bool
	usesUnion      bool
}

func main() {
	specPath := flag.String("spec", "", "OpenAPI JSON specification")
	outPath := flag.String("out", "", "generated Go output path")
	packageName := flag.String("package", "devin", "Go package name")
	optionalImport := flag.String("support-import", "", "package import path that provides Optional[T]")
	flag.Parse()
	if *specPath == "" || *outPath == "" {
		fmt.Fprintln(os.Stderr, "genmodels: -spec and -out are required")
		os.Exit(2)
	}
	spec, err := os.ReadFile(*specPath)
	if err != nil {
		fatal(err)
	}
	generated, err := generate(spec, *packageName, *optionalImport)
	if err != nil {
		fatal(err)
	}
	if err := os.WriteFile(*outPath, generated, 0o644); err != nil {
		fatal(err)
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "genmodels:", err)
	os.Exit(1)
}

func generate(specBytes []byte, packageName, optionalImport string) ([]byte, error) {
	var doc document
	if err := json.Unmarshal(specBytes, &doc); err != nil {
		return nil, fmt.Errorf("decode OpenAPI spec: %w", err)
	}
	if packageName == "" {
		return nil, errors.New("package name cannot be empty")
	}
	if len(doc.Components.Schemas) == 0 {
		return nil, errors.New("OpenAPI spec has no component schemas")
	}
	g := &generator{
		packageName: packageName, optionalImport: optionalImport,
		schemas: doc.Components.Schemas, declared: make(map[string]bool),
		declaredSchema: make(map[string]*schema), componentNames: make(map[string]string),
	}
	names := make([]string, 0, len(g.schemas))
	for name := range g.schemas {
		names = append(names, name)
	}
	sort.Strings(names)
	goNames := make(map[string]string, len(names))
	for _, name := range names {
		goName := codegen.GoName(name)
		if previous, exists := goNames[goName]; exists {
			return nil, fmt.Errorf("schemas %q and %q normalize to the same Go name %q", previous, name, goName)
		}
		goNames[goName] = name
		g.componentNames[goName] = name
	}
	for _, name := range names {
		if err := g.emitNamed(codegen.GoName(name), g.schemas[name]); err != nil {
			return nil, fmt.Errorf("schema %q: %w", name, err)
		}
	}

	var src strings.Builder
	fmt.Fprintf(&src, "// Code generated by genmodels; DO NOT EDIT.\n\npackage %s\n", packageName)
	imports := make([]string, 0, 4)
	if g.usesJSON {
		imports = append(imports, "\"encoding/json\"")
	}
	if g.usesUnion {
		imports = append(imports, "\"bytes\"", "\"errors\"")
	}
	if g.usesOptional && optionalImport != "" {
		imports = append(imports, "devin "+strconv.Quote(optionalImport))
	}
	if len(imports) != 0 {
		src.WriteString("\nimport (\n")
		for _, imp := range imports {
			fmt.Fprintf(&src, "\t%s\n", imp)
		}
		src.WriteString(")\n")
	}
	src.WriteByte('\n')
	for _, decl := range g.decls {
		src.WriteString(decl)
		src.WriteByte('\n')
	}
	formatted, err := format.Source([]byte(src.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w\n%s", err, src.String())
	}
	return formatted, nil
}

func (g *generator) emitNamed(name string, s *schema) error {
	if component, exists := g.componentNames[name]; exists && g.schemas[component] != s {
		return fmt.Errorf("nested type %q collides with component schema %q", name, component)
	}
	if g.declared[name] {
		if g.declaredSchema[name] != s {
			return fmt.Errorf("multiple inline schemas normalize to generated type name %q", name)
		}
		return nil
	}
	g.declared[name] = true
	g.declaredSchema[name] = s
	if s == nil {
		return errors.New("schema is empty")
	}
	s = normalizeNullUnion(s)
	if s.Ref != "" {
		ref, err := g.resolveRef(s.Ref)
		if err != nil {
			return err
		}
		g.decls = append(g.decls, fmt.Sprintf("%s\ntype %s = %s\n", docComment(name, s.Description), name, ref))
		return nil
	}
	if len(s.AllOf) > 0 {
		if len(s.AllOf) == 1 && s.AllOf[0].Ref != "" {
			ref, err := g.resolveRef(s.AllOf[0].Ref)
			if err != nil {
				return err
			}
			g.decls = append(g.decls, fmt.Sprintf("%s\ntype %s = %s\n", docComment(name, s.Description), name, ref))
			return nil
		}
		merged, err := g.flattenAllOf(s.AllOf)
		if err != nil {
			return err
		}
		s = merged
	}
	if len(s.Enum) > 0 {
		return g.emitEnum(name, s)
	}
	if len(s.OneOf) > 0 || len(s.AnyOf) > 0 {
		return g.emitUnion(name, s)
	}
	if len(s.Properties) > 0 || s.Type == "object" {
		return g.emitObject(name, s)
	}
	if s.Type == "array" {
		if len(s.PrefixItems) > 0 {
			item, err := g.tupleItemType(name, s.PrefixItems)
			if err != nil {
				return err
			}
			g.decls = append(g.decls, fmt.Sprintf("%s\ntype %s [%d]%s\n", docComment(name, s.Description), name, len(s.PrefixItems), item))
			return nil
		}
		item, err := g.typeExpr(name+"Item", s.Items)
		if err != nil {
			return err
		}
		g.decls = append(g.decls, fmt.Sprintf("%s\ntype %s []%s\n", docComment(name, s.Description), name, item))
		return nil
	}
	base, err := g.scalarType(s.Type)
	if err != nil {
		return err
	}
	if base == "json.RawMessage" {
		g.decls = append(g.decls, fmt.Sprintf("%s\ntype %s = json.RawMessage\n", docComment(name, s.Description), name))
		return nil
	}
	g.decls = append(g.decls, fmt.Sprintf("%s\ntype %s %s\n", docComment(name, s.Description), name, base))
	return nil
}

func (g *generator) emitObject(name string, s *schema) error {
	if len(s.Properties) == 0 && !isFalseJSON(s.AdditionalProperties) {
		valueType, err := g.mapValueType(name, s.AdditionalProperties)
		if err != nil {
			return err
		}
		g.decls = append(g.decls, fmt.Sprintf("%s\ntype %s map[string]%s\n", docComment(name, s.Description), name, valueType))
		return nil
	}
	props := make([]string, 0, len(s.Properties))
	for property := range s.Properties {
		props = append(props, property)
	}
	sort.Strings(props)
	required := make(map[string]bool, len(s.Required))
	for _, prop := range s.Required {
		required[prop] = true
	}
	var body strings.Builder
	fmt.Fprintf(&body, "%s\ntype %s struct {\n", docComment(name, s.Description), name)
	used := make(map[string]bool)
	for _, property := range props {
		fieldName := codegen.GoName(property)
		if used[fieldName] {
			return fmt.Errorf("properties collide after Go name normalization at %q", property)
		}
		used[fieldName] = true
		propertySchema := s.Properties[property]
		fieldType, err := g.fieldType(name+fieldName, propertySchema, required[property])
		if err != nil {
			return fmt.Errorf("property %q: %w", property, err)
		}
		tag := property
		if !required[property] {
			tag += ",omitempty"
		}
		fieldDescription := "JSON field " + strconv.Quote(property) + "."
		if propertySchema != nil && propertySchema.Description != "" {
			fieldDescription = propertySchema.Description
		}
		fmt.Fprintf(&body, "\t%s\n\t%s %s `json:%s`\n", commentText(fieldDescription), fieldName, fieldType, strconv.Quote(tag))
	}
	if len(s.Properties) == 0 {
		body.WriteString("\t_ struct{} `json:\"-\"`\n")
	}
	body.WriteString("}\n")
	g.decls = append(g.decls, body.String())
	return nil
}

func (g *generator) fieldType(owner string, s *schema, required bool) (string, error) {
	if s == nil {
		g.usesJSON = true
		return "json.RawMessage", nil
	}
	s = normalizeNullUnion(s)
	base, err := g.typeExpr(owner, s)
	if err != nil {
		return "", err
	}
	// json.RawMessage preserves a JSON null as bytes, but *json.RawMessage
	// does not: encoding/json sets the pointer to nil and omitempty drops the
	// property on re-encode. Use Optional to keep unset and explicit null apart.
	if !required && (s.Nullable || g.isOpaqueJSONSchema(s, make(map[string]bool))) {
		g.usesOptional = true
		if g.optionalImport == "" {
			return "Optional[" + base + "]", nil
		}
		return "devin.Optional[" + base + "]", nil
	}
	if s.Nullable {
		if required {
			if !g.isMapOrArraySchema(s, make(map[string]bool)) {
				return "*" + base, nil
			}
			return base, nil
		}
	}
	if !required {
		return "*" + base, nil
	}
	return base, nil
}

func (g *generator) isOpaqueJSONSchema(s *schema, seen map[string]bool) bool {
	if s == nil {
		return true
	}
	if s.Ref != "" {
		name := strings.TrimPrefix(s.Ref, "#/components/schemas/")
		if seen[name] {
			return false
		}
		seen[name] = true
		return g.isOpaqueJSONSchema(g.schemas[name], seen)
	}
	if len(s.AllOf) == 1 {
		return g.isOpaqueJSONSchema(s.AllOf[0], seen)
	}
	if len(s.AnyOf) == 1 {
		return g.isOpaqueJSONSchema(s.AnyOf[0], seen)
	}
	if len(s.OneOf) == 1 {
		return g.isOpaqueJSONSchema(s.OneOf[0], seen)
	}
	return (s.Type == "" || s.Type == "null") && len(s.Properties) == 0 && len(s.Enum) == 0 && len(s.AnyOf) == 0 && len(s.OneOf) == 0 && len(s.AllOf) == 0 && len(s.AdditionalProperties) == 0
}

func (g *generator) typeExpr(owner string, s *schema) (string, error) {
	if s == nil {
		g.usesJSON = true
		return "json.RawMessage", nil
	}
	if s.Ref != "" {
		return g.resolveRef(s.Ref)
	}
	s = normalizeNullUnion(s)
	if len(s.AllOf) > 0 {
		if len(s.AllOf) == 1 {
			return g.typeExpr(owner, s.AllOf[0])
		}
		merged, err := g.flattenAllOf(s.AllOf)
		if err != nil {
			return "", err
		}
		s = merged
	}
	if len(s.OneOf) == 1 {
		return g.typeExpr(owner, s.OneOf[0])
	}
	if len(s.AnyOf) == 1 {
		return g.typeExpr(owner, s.AnyOf[0])
	}
	if len(s.Enum) > 0 || len(s.OneOf) > 0 || len(s.AnyOf) > 0 || len(s.Properties) > 0 || (s.Type == "object" && (len(s.AdditionalProperties) == 0 || isFalseJSON(s.AdditionalProperties))) {
		if err := g.emitNamed(owner, s); err != nil {
			return "", err
		}
		return owner, nil
	}
	if s.Type == "array" {
		if len(s.PrefixItems) > 0 {
			itemType, err := g.tupleItemType(owner, s.PrefixItems)
			if err != nil {
				return "", err
			}
			return "[" + strconv.Itoa(len(s.PrefixItems)) + "]" + itemType, nil
		}
		item, err := g.typeExpr(owner+"Item", s.Items)
		if err != nil {
			return "", err
		}
		return "[]" + item, nil
	}
	if s.Type == "object" || len(s.AdditionalProperties) > 0 {
		valueType, err := g.mapValueType(owner, s.AdditionalProperties)
		if err != nil {
			return "", err
		}
		return "map[string]" + valueType, nil
	}
	if s.Type == "" {
		g.usesJSON = true
		return "json.RawMessage", nil
	}
	return g.scalarType(s.Type)
}

func (g *generator) emitEnum(name string, s *schema) error {
	base := "string"
	if s.Type != "" {
		var err error
		base, err = g.scalarType(s.Type)
		if err != nil {
			return err
		}
	}
	var out strings.Builder
	fmt.Fprintf(&out, "%s\ntype %s %s\n\nconst (\n", docComment(name, s.Description), name, base)
	used := make(map[string]int)
	for _, raw := range s.Enum {
		var value any
		if err := json.Unmarshal(raw, &value); err != nil {
			return err
		}
		literal, err := json.Marshal(value)
		if err != nil {
			return err
		}
		constant := name + codegen.GoName(fmt.Sprint(value))
		used[constant]++
		if used[constant] > 1 {
			constant += strconv.Itoa(used[constant])
		}
		fmt.Fprintf(&out, "\t%s\n\t%s %s = %s\n", commentText("Value "+fmt.Sprint(value)+" for "+name+"."), constant, name, literal)
	}
	out.WriteString(")\n")
	g.decls = append(g.decls, out.String())
	return nil
}

func (g *generator) emitUnion(name string, s *schema) error {
	variants := s.OneOf
	if len(variants) == 0 {
		variants = s.AnyOf
	}
	if len(variants) == 0 {
		g.usesJSON = true
		g.decls = append(g.decls, fmt.Sprintf("%s\ntype %s = json.RawMessage\n", docComment(name, s.Description), name))
		return nil
	}
	g.usesJSON, g.usesUnion = true, true
	var out strings.Builder
	fmt.Fprintf(&out, `%s
type %s struct { raw json.RawMessage }

// MarshalJSON writes the union's stored JSON value.
func (value %s) MarshalJSON() ([]byte, error) {
	if len(value.raw) == 0 { return []byte("null"), nil }
	if !json.Valid(value.raw) { return nil, errors.New("invalid %s union JSON") }
	return append([]byte(nil), value.raw...), nil
}

// UnmarshalJSON stores a copy of the input JSON value.
func (value *%s) UnmarshalJSON(data []byte) error {
	if value == nil { return errors.New("cannot unmarshal %s into a nil receiver") }
	if !json.Valid(data) { return errors.New("invalid %s union JSON") }
	value.raw = append(value.raw[:0], data...)
	return nil
}
`, docComment(name, s.Description), name, name, name, name, name, name)
	used := make(map[string]bool)
	for i, variant := range variants {
		variantType, err := g.typeExpr(name+"Variant"+strconv.Itoa(i+1), variant)
		if err != nil {
			return fmt.Errorf("variant %d: %w", i+1, err)
		}
		suffix := variantSuffix(variant, variantType, i)
		if used[suffix] {
			suffix += strconv.Itoa(i + 1)
		}
		used[suffix] = true
		fmt.Fprintf(&out, `
// New%s%s constructs the union from a %s value.
func New%s%s(value %s) (%s, error) {
	raw, err := json.Marshal(value)
	if err != nil { return %s{}, err }
	return %s{raw: raw}, nil
}

// As%s decodes the stored JSON as %s. It does not identify a oneOf variant
// when multiple object variants can accept the same JSON shape.
func (value %s) As%s() (%s, bool) {
	if len(value.raw) == 0 || bytes.Equal(bytes.TrimSpace(value.raw), []byte("null")) {
		var zero %s
		return zero, false
	}
	var result %s
	if err := json.Unmarshal(value.raw, &result); err != nil {
		var zero %s
		return zero, false
	}
	return result, true
}
		`, name, suffix, variantType, name, suffix, variantType, name, name, name,
			suffix, variantType, name, suffix, variantType, variantType, variantType, variantType)
	}
	g.decls = append(g.decls, out.String())
	return nil
}

func variantSuffix(s *schema, typeName string, index int) string {
	if s != nil && s.Ref != "" {
		return codegen.GoName(path.Base(s.Ref))
	}
	if s != nil {
		switch s.Type {
		case "string":
			return "String"
		case "integer":
			return "Integer"
		case "number":
			return "Number"
		case "boolean":
			return "Boolean"
		case "array":
			return "Array"
		case "object":
			return "Object"
		}
	}
	return codegen.GoName(typeName + strconv.Itoa(index+1))
}

func normalizeNullUnion(s *schema) *schema {
	if s == nil {
		return nil
	}
	if len(s.OneOf) == 0 && len(s.AnyOf) == 0 {
		return s
	}
	copySchema := *s
	changed := false
	filterNull := func(variants []*schema) []*schema {
		filtered := make([]*schema, 0, len(variants))
		for _, variant := range variants {
			if variant != nil && variant.Type == "null" {
				changed = true
				continue
			}
			filtered = append(filtered, variant)
		}
		return filtered
	}
	if len(s.OneOf) > 0 {
		copySchema.OneOf = filterNull(s.OneOf)
	}
	if len(s.AnyOf) > 0 {
		copySchema.AnyOf = filterNull(s.AnyOf)
	}
	if !changed {
		return s
	}
	copySchema.Nullable = true
	return &copySchema
}

func (g *generator) mapValueType(owner string, raw json.RawMessage) (string, error) {
	if len(raw) == 0 || bytes.Equal(bytes.TrimSpace(raw), []byte("true")) || isFalseJSON(raw) {
		g.usesJSON = true
		return "json.RawMessage", nil
	}
	var valueSchema schema
	if err := json.Unmarshal(raw, &valueSchema); err != nil {
		return "", fmt.Errorf("decode additionalProperties: %w", err)
	}
	return g.typeExpr(owner+"Value", &valueSchema)
}

func (g *generator) tupleItemType(owner string, items []*schema) (string, error) {
	if len(items) == 0 {
		g.usesJSON = true
		return "json.RawMessage", nil
	}
	first, err := json.Marshal(items[0])
	if err != nil {
		return "", err
	}
	for _, item := range items[1:] {
		encoded, err := json.Marshal(item)
		if err != nil {
			return "", err
		}
		if !bytes.Equal(first, encoded) {
			g.usesJSON = true
			return "json.RawMessage", nil
		}
	}
	return g.typeExpr(owner+"Item", items[0])
}

func isFalseJSON(raw json.RawMessage) bool {
	return bytes.Equal(bytes.TrimSpace(raw), []byte("false"))
}

func docComment(name, description string) string {
	if strings.TrimSpace(description) == "" {
		description = "OpenAPI schema " + name + "."
	}
	return commentText(description)
}

func commentText(text string) string {
	text = strings.Join(strings.Fields(text), " ")
	text = strings.ReplaceAll(text, "*/", "* /")
	if text == "" {
		text = "Generated API field."
	}
	return "// " + text
}

func (g *generator) scalarType(kind string) (string, error) {
	switch kind {
	case "string":
		return "string", nil
	case "integer":
		return "int64", nil
	case "number":
		return "float64", nil
	case "boolean":
		return "bool", nil
	case "null":
		g.usesJSON = true
		return "json.RawMessage", nil
	case "":
		g.usesJSON = true
		return "json.RawMessage", nil
	default:
		return "", fmt.Errorf("unsupported schema type %q", kind)
	}
}

func (g *generator) resolveRef(ref string) (string, error) {
	const prefix = "#/components/schemas/"
	if !strings.HasPrefix(ref, prefix) {
		return "", fmt.Errorf("unsupported reference %q", ref)
	}
	name := strings.TrimPrefix(ref, prefix)
	name = strings.ReplaceAll(strings.ReplaceAll(name, "~1", "/"), "~0", "~")
	if _, ok := g.schemas[name]; !ok {
		return "", fmt.Errorf("reference %q does not exist", ref)
	}
	return codegen.GoName(name), nil
}

func (g *generator) flattenAllOf(parts []*schema) (*schema, error) {
	merged := &schema{Type: "object", Properties: make(map[string]*schema)}
	required := make(map[string]bool)
	for _, part := range parts {
		if part == nil {
			continue
		}
		if part.Ref != "" {
			refName := strings.TrimPrefix(part.Ref, "#/components/schemas/")
			refName = strings.ReplaceAll(strings.ReplaceAll(refName, "~1", "/"), "~0", "~")
			refSchema, ok := g.schemas[refName]
			if !ok {
				return nil, fmt.Errorf("reference %q does not exist", part.Ref)
			}
			part = refSchema
		}
		if len(part.AllOf) > 0 {
			flattened, err := g.flattenAllOf(part.AllOf)
			if err != nil {
				return nil, err
			}
			part = flattened
		}
		for property, propertySchema := range part.Properties {
			merged.Properties[property] = propertySchema
		}
		for _, property := range part.Required {
			required[property] = true
		}
	}
	for property := range required {
		merged.Required = append(merged.Required, property)
	}
	sort.Strings(merged.Required)
	return merged, nil
}

func (g *generator) isMapOrArraySchema(s *schema, seen map[string]bool) bool {
	if s == nil {
		return false
	}
	if s.Ref != "" {
		const prefix = "#/components/schemas/"
		if !strings.HasPrefix(s.Ref, prefix) {
			return false
		}
		name := strings.TrimPrefix(s.Ref, prefix)
		name = strings.ReplaceAll(strings.ReplaceAll(name, "~1", "/"), "~0", "~")
		if seen[name] {
			return false
		}
		seen[name] = true
		return g.isMapOrArraySchema(g.schemas[name], seen)
	}
	if len(s.AllOf) == 1 {
		return g.isMapOrArraySchema(s.AllOf[0], seen)
	}
	if len(s.OneOf) == 1 {
		return g.isMapOrArraySchema(s.OneOf[0], seen)
	}
	if len(s.AnyOf) == 1 {
		return g.isMapOrArraySchema(s.AnyOf[0], seen)
	}
	if s.Type == "array" {
		return true
	}
	return s.Type == "object" && len(s.Properties) == 0 && len(s.AdditionalProperties) != 0 && !isFalseJSON(s.AdditionalProperties)
}
