import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"devingo/internal/codegen"
)

func render(endpoints []*endpoint, cfg config) ([]byte, error) {
	imports := map[string]string{"context": "context"}
	if cfg.Legacy != "" {
		imports["devingo"] = "devin"
	}
	groups := map[string]map[string]bool{"org": {}, "enterprise": {}, "global": {}}
	for _, ep := range endpoints {
		if ep.Scope != "global" || cfg.Legacy != "" {
			groups[ep.Scope][ep.Service] = true
		}
		if len(ep.PathParams) > 0 || ep.Scope == "org" || len(ep.QueryParams) > 0 {
			imports["net/url"] = "url"
		}
		if len(ep.PathParams) > 0 || ep.Scope == "org" || ep.Multipart || (ep.Operation.RequestBody != nil && ep.Operation.RequestBody.Required) {
			imports["fmt"] = "fmt"
		}
		if strings.Contains(ep.RequestType, "json.RawMessage") || strings.Contains(ep.ResponseType, "json.RawMessage") {
			imports["encoding/json"] = "json"
		}
		for _, p := range ep.QueryParams {
			kind := queryKind(p.Schema)
			if kind == "int64" || kind == "bool" || kind == "float64" || strings.HasPrefix(kind, "[]int64") || strings.HasPrefix(kind, "[]bool") || strings.HasPrefix(kind, "[]float64") {
				imports["strconv"] = "strconv"
			}
			if p.Required {
				imports["fmt"] = "fmt"
			}
		}
	}
	var source bytes.Buffer
	fmt.Fprintf(&source, "// Code generated by genservices; DO NOT EDIT.\n\npackage %s\n\n", cfg.Package)
	source.WriteString("import (\n")
	for _, path := range sortedKeys(imports) {
		name := imports[path]
		if name == path {
			fmt.Fprintf(&source, "\t%q\n", path)
		} else {
			fmt.Fprintf(&source, "\t%s %q\n", name, path)
		}
	}
	source.WriteString(")\n\n")
	if cfg.Legacy != "" {
		emitLegacyClient(&source, groups["global"])
	}
	if len(groups["org"]) > 0 {
		emitScope(&source, cfg, "org", groups["org"])
	}
	if len(groups["enterprise"]) > 0 {
		emitScope(&source, cfg, "enterprise", groups["enterprise"])
	}
	if cfg.Legacy != "" {
		for _, service := range sortedSet(groups["global"]) {
			fmt.Fprintf(&source, "type %s struct { client *devin.Client }\n\n", serviceType("global", service))
		}
	}
	for _, ep := range endpoints {
		if len(ep.QueryParams) > 0 {
			emitOptions(&source, ep)
		}
		if err := emitMethod(&source, ep, cfg); err != nil {
			return nil, fmt.Errorf("%s %s: %w", ep.HTTPMethod, ep.Path, err)
		}
	}
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated services: %w\n%s", err, source.String())
	}
	return formatted, nil
}

func sortedSet(values map[string]bool) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func serviceType(scope, service string) string {
	switch scope {
	case "org":
		return "Org" + service + "Service"
	case "enterprise":
		return "Enterprise" + service + "Service"
	default:
		return "Global" + service + "Service"
	}
}

func emitLegacyClient(out *bytes.Buffer, globals map[string]bool) {
	out.WriteString("// Client wraps the shared Devin transport with legacy API services.\n")
	out.WriteString("type Client struct {\n\t*devin.Client\n")
	for _, service := range sortedSet(globals) {
		fmt.Fprintf(out, "\t%s %s\n", service, serviceType("global", service))
	}
	out.WriteString("}\n\n")
	out.WriteString("// NewClient creates a legacy API client.\n")
	out.WriteString("func NewClient(token string, opts ...devin.Option) (*Client, error) {\n")
	out.WriteString("\ttransport, err := devin.NewClient(token, opts...)\n\tif err != nil { return nil, err }\n")
	out.WriteString("\tclient := &Client{Client: transport}\n")
	for _, service := range sortedSet(globals) {
		fmt.Fprintf(out, "\tclient.%s = %s{client: transport}\n", service, serviceType("global", service))
	}
	out.WriteString("\treturn client, nil\n}\n\n")
}

func emitScope(out *bytes.Buffer, cfg config, scope string, services map[string]bool) {
	clientType := "*Client"
	transportType := "*Client"
	if cfg.Legacy != "" {
		transportType = "*devin.Client"
	}
	name := "OrganizationClient"
	if scope == "enterprise" {
		name = "EnterpriseClient"
	}
	fmt.Fprintf(out, "// %s groups %s API services.\ntype %s struct {\n\tclient %s\n", name, scope, name, transportType)
	if scope == "org" {
		out.WriteString("\torgID string\n")
	}
	for _, service := range sortedSet(services) {
		fmt.Fprintf(out, "\t%s %s\n", service, serviceType(scope, service))
	}
	out.WriteString("}\n\n")
	if scope == "org" {
		fmt.Fprintf(out, "// Organization selects an organization.\nfunc (c %s) Organization(orgID string) *%s {\n", clientType, name)
	} else {
		fmt.Fprintf(out, "// Enterprise selects enterprise services.\nfunc (c %s) Enterprise() *%s {\n", clientType, name)
	}
	transportExpr := "c"
	if cfg.Legacy != "" {
		transportExpr = "c.Client"
	}
	if scope == "org" {
		fmt.Fprintf(out, "\tscope := &%s{client: %s, orgID: orgID}\n", name, transportExpr)
	} else {
		fmt.Fprintf(out, "\tscope := &%s{client: %s}\n", name, transportExpr)
	}
	for _, service := range sortedSet(services) {
		fmt.Fprintf(out, "\tscope.%s = %s{scope: scope}\n", service, serviceType(scope, service))
	}
	out.WriteString("\treturn scope\n}\n\n")
	for _, service := range sortedSet(services) {
		fmt.Fprintf(out, "// %s provides %s endpoints.\ntype %s struct { scope *%s }\n\n", serviceType(scope, service), service, serviceType(scope, service), name)
	}
}

func optionsType(ep *endpoint) string {
	switch ep.Scope {
	case "org":
		return "Org" + ep.Service + ep.Method + "Options"
	case "enterprise":
		return "Enterprise" + ep.Service + ep.Method + "Options"
	default:
		return "Global" + ep.Service + ep.Method + "Options"
	}
}

func queryKind(s *schema) string {
	if s == nil {
		return "string"
	}
	if s.Ref != "" || s.Type == "object" || len(s.Properties) > 0 || len(s.AdditionalProperties) > 0 {
		return "url.Values"
	}
	for _, branch := range append(append([]*schema{}, s.AnyOf...), s.OneOf...) {
		if branch != nil && branch.Type != "null" {
			return queryKind(branch)
		}
	}
	switch s.Type {
	case "integer":
		return "int64"
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "array":
		return "[]" + queryKind(s.Items)
	default:
		return "string"
	}
}

func emitOptions(out *bytes.Buffer, ep *endpoint) {
	name := optionsType(ep)
	fmt.Fprintf(out, "// %s configures query parameters for %s.\ntype %s struct {\n", name, ep.Method, name)
	out.WriteString("\tExtra url.Values // Additional query parameters; typed fields take precedence.\n")
	used := map[string]bool{}
	for _, p := range ep.QueryParams {
		field := safeFieldName(p.Name)
		if used[field] {
			field += "Value"
		}
		used[field] = true
		typ := queryKind(p.Schema)
		if !p.Required && typ != "url.Values" && !strings.HasPrefix(typ, "[]") {
			typ = "*" + typ
		}
		fmt.Fprintf(out, "\t%s %s\n", field, typ)
	}
	out.WriteString("}\n\n")
}

func safeFieldName(name string) string {
	field := codegen.GoName(name)
	if field == "" {
		return "Value"
	}
	return field
}

func lowerName(name string) string {
	if name == "" {
		return "value"
	}
	runes := []rune(name)
	last := 0
	for last+1 < len(runes) && unicode.IsUpper(runes[last+1]) {
		if last+2 < len(runes) && unicode.IsLower(runes[last+2]) {
			break
		}
		last++
	}
	for i := 0; i <= last; i++ {
		runes[i] = unicode.ToLower(runes[i])
	}
	result := string(runes)
	if result == "type" || result == "range" || result == "map" || result == "var" || result == "func" || result == "interface" || result == "select" || result == "go" || result == "chan" || result == "defer" || result == "default" {
		return result + "Value"
	}
	return result
}

func emitMethod(out *bytes.Buffer, ep *endpoint, cfg config) error {
	responseName := "Response"
	if cfg.Legacy != "" {
		responseName = "devin.Response"
	}
	receiver := "c *Client"
	callTarget := "c"
	if ep.Scope != "global" || cfg.Legacy != "" {
		receiver = "s " + serviceType(ep.Scope, ep.Service)
		callTarget = "s.client"
		if ep.Scope != "global" {
			callTarget = "s.scope.client"
		}
	}
	args := []string{"ctx context.Context"}
	for _, p := range ep.PathParams {
		args = append(args, lowerName(safeFieldName(p.Name))+" string")
	}
	if ep.RequestType != "" {
		argName := "request"
		if ep.Multipart {
			argName = "file"
		}
		args = append(args, argName+" *"+ep.RequestType)
	}
	if len(ep.QueryParams) > 0 {
		args = append(args, "opts *"+optionsType(ep))
	}
	returns := "(*" + responseName + ", error)"
	if ep.Redirect {
		returns = "(string, *" + responseName + ", error)"
	} else if ep.HasResponse {
		returns = "(*" + ep.ResponseType + ", *" + responseName + ", error)"
	}
	comment := ep.Operation.Summary
	if comment == "" {
		comment = ep.HTTPMethod + " " + ep.Path
	}
	comment = strings.ReplaceAll(strings.ReplaceAll(comment, "\n", " "), "\r", " ")
	fmt.Fprintf(out, "// %s %s.\n", ep.Method, strings.TrimSuffix(comment, "."))
	if ep.Operation.DocURL != "" {
		fmt.Fprintf(out, "// See %s.\n", ep.Operation.DocURL)
	}
	if ep.Operation.ContractGap != "" {
		gap := strings.ReplaceAll(strings.ReplaceAll(ep.Operation.ContractGap, "\n", " "), "\r", " ")
		fmt.Fprintf(out, "// Contract limitation: %s\n", gap)
	}
	if strings.Contains(ep.Path, "/v3beta1/") || strings.HasPrefix(ep.Path, "/beta/") {
		out.WriteString("// This endpoint is part of the beta API and may change.\n")
	}
	fmt.Fprintf(out, "func (%s) %s(%s) %s {\n", receiver, ep.Method, strings.Join(args, ", "), returns)
	var zero string
	if ep.Redirect {
		zero = "\"\", nil, "
	} else if ep.HasResponse {
		zero = "nil, nil, "
	} else {
		zero = "nil, "
	}
	if ep.Scope == "org" {
		fmt.Fprintf(out, "\tif s.scope.orgID == \"\" { return %sfmt.Errorf(%q) }\n", zero, "devin: organization ID is required")
	}
	for _, p := range ep.PathParams {
		arg := lowerName(safeFieldName(p.Name))
		fmt.Fprintf(out, "\tif %s == \"\" { return %sfmt.Errorf(%q) }\n", arg, zero, "devin: "+p.Name+" is required")
	}
	if ep.RequestType != "" && ep.Operation.RequestBody != nil && ep.Operation.RequestBody.Required {
		arg := "request"
		if ep.Multipart {
			arg = "file"
		}
		fmt.Fprintf(out, "\tif %s == nil { return %sfmt.Errorf(%q) }\n", arg, zero, "devin: "+arg+" is required")
	}
	pathExpression, err := buildPathExpression(ep.Path, ep.Scope)
	if err != nil {
		return err
	}
	fmt.Fprintf(out, "\tpath := %s\n", pathExpression)
	queryExpr := "nil"
	if len(ep.QueryParams) > 0 {
		queryExpr = "query"
		out.WriteString("\tquery := url.Values{}\n")
		for _, p := range ep.QueryParams {
			if p.Required {
				fmt.Fprintf(out, "\tif opts == nil { return %sfmt.Errorf(%q) }\n", zero, "devin: query options are required")
				break
			}
		}
		out.WriteString("\tif opts != nil {\n")
		out.WriteString("\t\tfor key, values := range opts.Extra { query[key] = append([]string(nil), values...) }\n")
		for _, p := range ep.QueryParams {
			if err := emitQueryParam(out, p, zero); err != nil {
				return err
			}
		}
		out.WriteString("\t}\n")
	}
	call := ""
	if ep.Redirect {
		call = fmt.Sprintf("%s.RedirectURL(ctx, path, %s)", callTarget, queryExpr)
	} else if ep.Multipart {
		resultArg := "nil"
		if ep.HasResponse {
			resultArg = "result"
		}
		call = fmt.Sprintf("%s.Upload(ctx, %q, path, %s, nil, \"file\", file, %s)", callTarget, ep.HTTPMethod, queryExpr, resultArg)
	} else {
		requestArg := "nil"
		if ep.RequestType != "" {
			requestArg = "request"
			if ep.Operation.RequestBody != nil && !ep.Operation.RequestBody.Required {
				out.WriteString("\tvar body any\n\tif request != nil { body = request }\n")
				requestArg = "body"
			}
		}
		resultArg := "nil"
		if ep.HasResponse {
			resultArg = "result"
		}
		call = fmt.Sprintf("%s.Do(ctx, %q, path, %s, %s, %s)", callTarget, ep.HTTPMethod, queryExpr, requestArg, resultArg)
	}
	if ep.Redirect {
		fmt.Fprintf(out, "\treturn %s\n", call)
	} else if ep.HasResponse {
		fmt.Fprintf(out, "\tresult := new(%s)\n", ep.ResponseType)
		fmt.Fprintf(out, "\tresponse, err := %s\n", call)
		out.WriteString("\tif err != nil { return nil, response, err }\n")
		out.WriteString("\treturn result, response, nil\n")
	} else {
		fmt.Fprintf(out, "\treturn %s\n", call)
	}
	out.WriteString("}\n\n")
	return nil
}

func emitQueryParam(out *bytes.Buffer, p parameter, zero string) error {
	field := "opts." + safeFieldName(p.Name)
	kind := queryKind(p.Schema)
	name := strconv.Quote(p.Name)
	if kind == "url.Values" {
		if p.Required {
			fmt.Fprintf(out, "\t\tif %s == nil { return %sfmt.Errorf(%q) }\n", field, zero, "devin: "+p.Name+" is required")
		}
		fmt.Fprintf(out, "\t\tfor key, values := range %s { query[key] = append([]string(nil), values...) }\n", field)
		return nil
	}
	if strings.HasPrefix(kind, "[]") {
		if p.Required {
			fmt.Fprintf(out, "\t\tif %s == nil { return %sfmt.Errorf(%q) }\n", field, zero, "devin: "+p.Name+" is required")
		}
		fmt.Fprintf(out, "\t\tif %s != nil { delete(query, %s); for _, value := range %s { query.Add(%s, %s) } }\n", field, name, field, name, stringExpression(strings.TrimPrefix(kind, "[]"), "value"))
		return nil
	}
	if p.Required {
		if kind == "string" {
			fmt.Fprintf(out, "\t\tif %s == \"\" { return %sfmt.Errorf(%q) }\n", field, zero, "devin: "+p.Name+" is required")
		}
		fmt.Fprintf(out, "\t\tquery.Set(%s, %s)\n", name, stringExpression(kind, field))
	} else {
		fmt.Fprintf(out, "\t\tif %s != nil { query.Set(%s, %s) }\n", field, name, stringExpression(kind, "*"+field))
	}
	return nil
}

func stringExpression(kind, value string) string {
	switch kind {
	case "int64":
		return "strconv.FormatInt(" + value + ", 10)"
	case "float64":
		return "strconv.FormatFloat(" + value + ", 'f', -1, 64)"
	case "bool":
		return "strconv.FormatBool(" + value + ")"
	default:
		return value
	}
}

func buildPathExpression(path, scope string) (string, error) {
	parts := pathVariableRE.FindAllStringSubmatchIndex(path, -1)
	if len(parts) == 0 {
		return strconv.Quote(path), nil
	}
	var expressions []string
	start := 0
	for _, match := range parts {
		if match[0] > start {
			expressions = append(expressions, strconv.Quote(path[start:match[0]]))
		}
		name := path[match[2]:match[3]]
		value := lowerName(safeFieldName(name))
		if name == "org_id" && scope == "org" {
			value = "s.scope.orgID"
		}
		expressions = append(expressions, "url.PathEscape("+value+")")
		start = match[1]
	}
	if start < len(path) {
		expressions = append(expressions, strconv.Quote(path[start:]))
	}
	if len(expressions) == 0 {
		return "", errors.New("empty path expression")
	}
	return strings.Join(expressions, " + "), nil
}
